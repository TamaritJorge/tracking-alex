const EDAD_MAX_DIAS = 3652;   // 10 años: hasta donde llegan las curvas

// Búsqueda binaria + interpolación lineal de L, M y S
function lmsEn(dias) {
  if (!(dias >= 0) || dias > EDAD_MAX_DIAS) return null;
  const t = LMS_PESO_NINOS;
  if (dias <= t[0][0]) return { L: t[0][1], M: t[0][2], S: t[0][3] };

  let lo = 0, hi = t.length - 1;
  while (hi - lo > 1) {
    const m = (lo + hi) >> 1;
    if (t[m][0] <= dias) lo = m; else hi = m;
  }
  const a = t[lo], b = t[hi];
  const f = (dias - a[0]) / (b[0] - a[0]);
  return {
    L: a[1] + f * (b[1] - a[1]),
    M: a[2] + f * (b[2] - a[2]),
    S: a[3] + f * (b[3] - a[3])
  };
}

// Peso (kg) correspondiente a una puntuación z
function pesoDeZ(lms, z) {
  const { L, M, S } = lms;
  return Math.abs(L) < 1e-9
    ? M * Math.exp(S * z)
    : M * Math.pow(1 + L * S * z, 1 / L);
}

// Puntuación z de un peso en kg
function zDePeso(lms, kg) {
  const { L, M, S } = lms;
  return Math.abs(L) < 1e-9
    ? Math.log(kg / M) / S
    : (Math.pow(kg / M, L) - 1) / (L * S);
}

// Función de distribución normal (Abramowitz-Stegun 7.1.26, error < 1e-7)
function normalCDF(z) {
  const s = z < 0 ? -1 : 1;
  const x = Math.abs(z) / Math.SQRT2;
  const t = 1 / (1 + 0.3275911 * x);
  const y = 1 - ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t
                  - 0.284496736) * t + 0.254829592) * t * Math.exp(-x * x);
  return 0.5 * (1 + s * y);
}

// z de los percentiles que se dibujan (valores exactos de la normal)
const Z_PERCENTIL = { 3: -1.880794, 15: -1.036433, 50: 0, 85: 1.036433, 97: 1.880794 };

function edadEnDias(fecha) {
  return (new Date(fecha) - FECHA_NACIMIENTO) / 864e5;
}

// Percentil OMS de una pesada. Devuelve null si la edad se sale de las curvas.
function percentilPeso(fechaISO, gramos) {
  const dias = edadEnDias(fechaISO);
  const lms  = lmsEn(dias);
  if (!lms || !(gramos > 0)) return null;
  const z = zDePeso(lms, gramos / 1000);
  return { z, pct: normalCDF(z) * 100, dias };
}

// Texto corto para enseñar el percentil sin fingir precisión en los extremos
function textoPercentil(pct) {
  if (pct < 0.1)  return '<P1';
  if (pct > 99.9) return '>P99';
  if (pct < 1)    return 'P' + pct.toFixed(1);
  if (pct > 99)   return 'P' + pct.toFixed(1);
  return 'P' + Math.round(pct);
}


/* ─────────────────────────────────────────────────────────────
   GANANCIA NECESARIA PARA NO BAJAR DE PERCENTIL

   Es la pendiente de la curva de la OMS que pasa por el punto
   actual: cuántos gramos al día tiene que ganar para quedarse
   donde está.

   No es constante ni de lejos. Para el percentil de Álex:
     1 semana  ~31 g/día      2 meses  ~28 g/día
     3 semanas ~40 g/día      3 meses  ~22 g/día
     1 mes     ~39 g/día      6 meses  ~12 g/día

   Por eso los 20 g/día de la pediatra no mantienen el percentil
   hasta pasados los ~3,3 meses: antes de esa edad son un suelo
   de alarma, no un objetivo.
   ───────────────────────────────────────────────────────────── */
function gananciaParaMantener(fechaISO, gramos) {
  const dias = edadEnDias(fechaISO);
  const lms  = lmsEn(dias);
  if (!lms || !(gramos > 0)) return null;

  const z = zDePeso(lms, gramos / 1000);

  // Derivada centrada en ±3 días, recortada a los bordes de la tabla
  const a = Math.max(0, dias - 3);
  const b = Math.min(EDAD_MAX_DIAS, dias + 3);
  const lmsA = lmsEn(a), lmsB = lmsEn(b);
  if (!lmsA || !lmsB || b - a <= 0) return null;

  return (pesoDeZ(lmsB, z) - pesoDeZ(lmsA, z)) / (b - a) * 1000;
}
